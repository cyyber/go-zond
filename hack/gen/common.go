package main

import (
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
)

// deterministicSeed produces a 51-byte ExtendedSeed hex string from a stable
// label. The label becomes part of a SHA-256 preimage so the full fixture set
// can be regenerated byte-for-byte from source without any network call.
//
// Layout: [descriptor(3 B)][seed(48 B)].
//   - descriptor = {0x01, 0x00, 0x00}  → ML-DSA-87, unchanged across runs.
//   - seed       = SHA-256("qrl-testgen-v1|" + label), truncated to 48 B, with
//     the last two bytes forced to 0 to match NewExtendedSeedFromBytes validation.
func deterministicSeed(label string) string {
	const descriptor = "010000"
	sum := sha256.Sum256([]byte("qrl-testgen-v1|" + label))
	var seed [48]byte
	copy(seed[:32], sum[:])
	// Stretch to 48 bytes by hashing the sum prefixed with a counter.
	for i := 32; i < 48; i += 8 {
		var ctr [9]byte
		copy(ctr[:], sum[:])
		binary.BigEndian.PutUint64(ctr[:8], uint64(i))
		extra := sha256.Sum256(ctr[:])
		copy(seed[i:], extra[:8])
	}
	seed[46] = 0
	seed[47] = 0
	return descriptor + hex.EncodeToString(seed[:])
}

// writeFile resolves path relative to outDir, creates parent directories, and
// writes payload atomically (.tmp rename).
func writeFile(outDir, relPath string, payload []byte) error {
	target := filepath.Join(outDir, relPath)
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	tmp := target + ".tmp"
	if err := os.WriteFile(tmp, payload, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, target)
}

// reportGenerated prints a short log line so the CLI caller can see which
// fixtures were (re)written.
func reportGenerated(kind, rel string) {
	fmt.Fprintf(os.Stdout, "  %-12s %s\n", kind, rel)
}
